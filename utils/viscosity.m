function eta = viscosity(T,H2O)

% Viscosity, Hui & Zhang 2007

SiO2 = 76.53e-2;
TiO2 = .06e-2;
Al2O3 = 13.01e-2;
FeO = .79e-2;
MnO = .08e-2;
MgO = .02e-2;
CaO = .74e-2;
Na2O = 3.87e-2;
K2O = 4.91e-2;

mO = 15.9994;
mSiO2 = 28.0855 + 2*mO;
mTiO2 = 47.88 + 2*mO;
mAl2O3 = 2*26.98154 + 3*mO;
mFeO = 55.847 + mO;
mMnO = 54.9380 + mO;
mMgO = 24.305 + mO;
mCaO = 40.08 + mO;
mNa2O = 2*22.98977 + mO;
mK2O = 2*39.0983 + mO;
mH2O = 2*1.00794 + mO;

nSiO2 = SiO2 / mSiO2;
    nTiO2 = TiO2 / mTiO2;
    nAl2O3 = Al2O3 / mAl2O3;
    nFeO = FeO / mFeO;
    nMnO = MnO / mMnO;
    nMgO = MgO / mMgO;
    nCaO = CaO / mCaO;
    nNa2O = Na2O / mNa2O;
    nK2O = K2O / mK2O;
%    nP2O5 = P2O5 / mP2O5;
    nH2O = H2O / mH2O;
    nFeMnO = nFeO + nMnO;
    
    nNaK = 2*nNa2O + 2*nK2O;
    nAl = 2*nAl2O3;
    if nNaK <= nAl
        nNaKAlO2 = nNaK;
        nAl2O3ex = (nAl-nNaK)/2;
        nNaK2Oex = 0;
    else
        nNaKAlO2 = nAl;
        nNaK2Oex = (nAl-nNaK)/2;
        nAl2O3ex = 0;
    end
    
    nmol = nSiO2 + nTiO2 + nFeMnO + ...
        nMgO + nCaO + nNaKAlO2 + nAl2O3ex + nNaK2Oex + nH2O;
    %
    XSiO2 = nSiO2./nmol;
    XTiO2 = nTiO2./nmol;
    XFeMnO = nFeMnO./nmol;
    XMgO = nMgO./nmol;
    XCaO = nCaO./nmol;
 %   XP2O5 = nP2O5./nmol;
 XP2O5 = 0;
    XNaKAlO2 = nNaKAlO2./nmol;
    XAl2O3ex = nAl2O3ex./nmol;
    XNaK2Oex = nNaK2Oex./nmol;
    XH2O = nH2O./nmol;
    %
    Z = XH2O.^(1./(1 + 185.797./T));
    
    eta = 10.^( ...
        ( ...
        -  6.83*XSiO2 ...
        - 170.79*XTiO2 ...
        - 14.71*XAl2O3ex ...
        - 18.01*XMgO ...
        - 19.76*XCaO ...
        - 34.31*XNaK2Oex ...
        - 140.38*Z ...
        + 159.26*XH2O ...
        - 8.43*XNaKAlO2 ...
        ) ...
        + ...
        ( ...
        + 18.14*XSiO2 ...
        + 248.93*XTiO2 ...
        + 32.61*XAl2O3ex ...
        + 25.96*XMgO ...
        + 22.64*XCaO ...
        - 68.29*XNaK2Oex ...
        + 38.84*Z ...
        - 48.55*XH2O ...
        + 16.12*XNaKAlO2 ...
        )* 1000./T ...
        + ...
        exp( ...
        ( ...
        + 21.73*XAl2O3ex ...
        - 61.98*XFeMnO ...
        - 105.53*XMgO ...
        - 69.92*XCaO ...
        - 85.67*XNaK2Oex ...
        + 332.01*Z ...
        - 432.22*XH2O ...
        - 3.16*XNaKAlO2 ...
        ) ...
        + ...
        ( ...
        + 2.16*XSiO2 ...
        - 143.05*XTiO2 ...
        - 22.10*XAl2O3ex ...
        + 38.56*XFeMnO ...
        + 110.83*XMgO ...
        + 67.12*XCaO ...
        + 58.01*XNaK2Oex ...
        + 384.77*XP2O5...
        - 404.97*Z ...
        + 513.75*XH2O ...
        )*1000./T ...
        ) ...
        );
end